import { writeFile } from "node:fs/promises"
import { join } from "node:path"

import zipcodes from "zipcodes"

// Writes a compact list of New York ZIP codes so the browser can validate
// addresses without bundling the full nationwide zipcodes dataset.
const codes = Object.values(zipcodes.codes)
  .filter((code) => code.state === "NY")
  .map((code) => code.zip)
  .sort()

const lines = []
for (let index = 0; index < codes.length; index += 12) {
  lines.push(`    "${codes.slice(index, index + 12).join(" ")}",`)
}

const source = `// Generated by scripts/generate-ny-zip-codes.mjs from the zipcodes package. Do not edit.
const NY_ZIP_CODES = new Set(
  [
${lines.join("\n")}
  ]
    .join(" ")
    .split(" ")
)

export function postalCodeError(postalCode: string) {
  const code = postalCode.trim()
  if (!code) return ""
  if (!/^\\d{5}$/.test(code)) return "Enter a five-digit ZIP code."
  if (!NY_ZIP_CODES.has(code)) return "Enter a New York ZIP code."
  return ""
}
`

await writeFile(join(process.cwd(), "lib", "ny-zip-codes.ts"), source)
console.log(`Wrote ${codes.length} New York ZIP codes.`)
